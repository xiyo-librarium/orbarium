import os, sys, subprocess, time, json
from playwright.sync_api import sync_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
os.makedirs('/tmp/orb_flow', exist_ok=True)
import mock_real
tag = sys.argv[1] if len(sys.argv) > 1 else 'f1'; W, H, DPR = (390, 844, 2) if 'phone' in tag else (1280, 820, 1)
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8807', '-d', os.path.join(HERE, '..', '..', 'public')], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
U = 'http://localhost:8807'
def shot(page, name, wait=900): page.wait_for_timeout(wait); page.screenshot(path=f'/tmp/orb_flow/{tag}_{name}.png')
def ready(page, t=120000): page.wait_for_function('window.__next && window.__next.v && window.__next.v.lastDraw', timeout=t)
try:
    with sync_playwright() as p:
        b = p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
        ctx = b.new_context(viewport={'width': W, 'height': H}, device_scale_factor=DPR)
        page = ctx.new_page()
        errs = []; page.on('pageerror', lambda e: errs.append('PE ' + str(e))); page.on('console', lambda m: errs.append(m.text[:200]) if m.type == 'error' else None)
        page.on('dialog', lambda d: d.accept())
        mock_real.install(page)
        page.goto(U + '/'); ready(page); shot(page, '0title')
        print('title buttons', page.evaluate("[...document.querySelectorAll('.title-card button')].map(b=>b.textContent)"))
        page.click('#newg'); page.wait_for_selector('.notif.in', timeout=8000); shot(page, '1notif', 700)
        print('notif', page.evaluate("document.querySelector('.notif').innerText.replace(/\\n/g,' / ')"))
        page.click('.notif'); page.wait_for_timeout(250); page.screenshot(path=f'/tmp/orb_flow/{tag}_1bopening.png'); shot(page, '1cmail', 500)
        print('mail subj', page.evaluate("document.querySelector('.mailview .mail-subj')?.textContent"))
        page.click('#go'); page.wait_for_timeout(1700); page.screenshot(path=f'/tmp/orb_flow/{tag}_2fly.png'); page.wait_for_function("window.__next.globe && window.__next.globe.userData.pins.some(m => m.userData.pin.id==='dest' && m.visible)", timeout=20000); page.wait_for_timeout(200); page.screenshot(path=f'/tmp/orb_flow/{tag}_2bpin.png')
        page.wait_for_url('**/?play**', timeout=20000)
        ready(page); shot(page, '3climate')
        print('url', page.url, 'climate', page.evaluate("document.querySelector('#reportBody h2')?.textContent"), 'site', page.evaluate("window.__next.s.site"), 'cash', page.evaluate("window.__next.s.cash"))
        page.click('#rBack'); shot(page, '4play')
        print('house cells', page.evaluate("Object.keys(window.__next.s.world.house.cells).length"), 'hasSave', page.evaluate("!!localStorage.getItem('orbarium-next-1')"))
        page.evaluate("window.__next.runSeason()"); page.wait_for_function("!document.querySelector('#report').hidden", timeout=60000); page.wait_for_timeout(800); page.click('#rBack', no_wait_after=True)
        page.goto(U + '/'); ready(page); shot(page, '5title_cont')
        print('cont', page.evaluate("document.querySelector('#cont')?.textContent"))
        page.click('#atl'); ready(page); shot(page, '6atlas')
        page.click('.atlas-card .list button >> nth=1'); shot(page, '7atlas_open')
        print('atlas open', page.evaluate("document.querySelector('.atlas-card b')?.textContent"), page.evaluate("document.querySelector('#read')?.textContent"))
        page.click('#read'); page.wait_for_timeout(300)
        print('atlas read', page.evaluate("localStorage.getItem('orbarium-next-atlas')"))
        page.click('#aback'); ready(page)
        page.click('#cont'); ready(page); shot(page, '8cont_play')
        print('resumed turn', page.evaluate("window.__next.s.turn"), 'url', page.url)
        # 章の終わりの代わり：持ち越しを入れて、アレンテージョへ（招待は報告かノートで読んであるので、地球儀ではすぐ飛ぶ）
        page.evaluate("""(() => { const s = window.__next.s; localStorage.setItem('orbarium-next-carry', JSON.stringify({ from: 'med', to: 'alen', cash: 200, persons: s.persons, known: s.known, learned: s.learned, year: s.year, q: s.q, invites: [{ land: 'ubud', from: 'med' }, { land: 'alen', from: 'med' }], history: [{ site: 'med', years: 1, rel: 5 }] })); location.href = '/?travel=alen'; })()""")
        page.wait_for_url('**travel=alen', timeout=20000); ready(page); shot(page, '9travel', 1500)
        print('travel notif', page.evaluate("!!document.querySelector('.notif')"))
        page.wait_for_url('**/?play**', timeout=20000); ready(page); shot(page, '10alen')
        print('alen', page.evaluate("window.__next.s.site"), 'cash', page.evaluate("window.__next.s.cash"), 'history', page.evaluate("JSON.stringify(window.__next.s.flags.history)"), 'invites', page.evaluate("JSON.stringify(window.__next.E.openInvites(window.__next.s).map(i=>i.land))"), 'carry left', page.evaluate("localStorage.getItem('orbarium-next-carry')"), 'climate', page.evaluate("document.querySelector('#reportBody h2')?.textContent"))
        page.click('#rBack'); page.wait_for_timeout(300)
        print('mailBtn', page.evaluate("!document.querySelector('#mailBtn').hidden"), page.evaluate("document.querySelector('#mailBtn').textContent"))
        print('ERRS', errs[:8])
finally:
    srv.terminate()
